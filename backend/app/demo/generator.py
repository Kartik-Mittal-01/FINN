def results_filing_text(u: dict, fin: dict, fy: int, q: int) -> str:
    cur, prev = qkey(fy, q), qkey(fy, q - 1) if q > 1 else qkey(fy - 1, 4)
    ya = qkey(fy - 1, q)
    Q = fin["quarterly"]
    d_cur, d_prev, d_ya = q_end(fy, q), q_end(fy - 1 if q == 1 else fy, 4 if q == 1 else q - 1), q_end(fy - 1, q)
    f = lambda d: d.strftime("%d.%m.%Y")
    hdr = f"Particulars | Quarter ended {f(d_cur)} | Quarter ended {f(d_prev)} | Quarter ended {f(d_ya)} | Half year ended {f(d_cur)} | Year ended 31.03.{2000 + fy - 1}"
    lines = [
        u["name"],
        f"Statement of Unaudited Consolidated Financial Results for the quarter ended {d_cur.strftime('%d %B %Y')}",
        "(Rs. in crore, except per share data)",
        "SAMPLE FILING TEXT - synthetic, generated by FINN's demo seeder. Not an actual exchange filing.",
        hdr,
    ]

    def row(label, key):
        vals = [Q.get(c, {}).get(key) for c in (cur, prev, ya)]
        if all(v is None for v in vals):
            return None
        return f"{label} | " + " | ".join(inr(v) for v in vals) + " | - | -"

    bank = u.get("bank")
    spec = [("Revenue from operations" if not bank else "Total income", "revenue")]
    if not bank:
        spec += [("Other income", "other_income"), ("Finance costs", "finance_cost"), ("Depreciation and amortisation expense", "depreciation")]
    spec += [("Profit before tax", "pbt"), ("Profit for the period", "pat")]
    for label, key in spec:
        rr = row(label, key)
        if rr:
            lines.append(rr)
    return "\n".join(lines)


