def business_days_back(end: date, n: int) -> list[date]:
    out, d = [], end
    while len(out) < n:
        if d.weekday() < 5:
            out.append(d)
        d -= timedelta(days=1)
    return out[::-1]


def generate_prices(u: dict, end: Optional[date] = None, n: int = 140) -> list[dict]:
    t = u["ticker"]
    r = _rng(t, "px")
    days = business_days_back(end or last_trading_day(), n)
    sd = 0.012 if u["size"] == "large" else 0.018
    rets = r.normal(0.0003, sd, n)
    closes = u["base"] * np.cumprod(1 + rets)
    closes = closes * (u["base"] / closes[-1])
    vols = u["vol"] * np.exp(r.normal(0, 0.22, n)) * (1 + 0.5 * np.abs(rets) / sd)
    ev = EVENTS.get(t)
    if ev:
        closes[-1] = closes[-2] * (1 + ev[0] / 100)
        vols[-1] = vols[-21:-1].mean() * ev[1]
    bars = []
    for i, d in enumerate(days):
        prev = closes[i - 1] if i else closes[i] / (1 + rets[i])
        o = prev * (1 + r.normal(0, 0.002))
        c = closes[i]
        h = max(o, c) * (1 + abs(r.normal(0, 0.004)))
        l = min(o, c) * (1 - abs(r.normal(0, 0.004)))
        bars.append(dict(ticker=t, date=d.isoformat(), open=round(o, 2), high=round(h, 2), low=round(l, 2), close=round(c, 2),
                         adj_close=round(c, 2), volume=float(round(vols[i])), source="demo"))
    return bars


