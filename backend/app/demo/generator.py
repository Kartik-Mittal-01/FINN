def _fmt(x):
    return "n/a" if x is None else f"Rs. {x:,.0f} crore"


def _round_to(x, base=50):
    return int(round(x / base) * base)


def guidance_plan(u: dict, fin: dict) -> dict:
    """Builds synthetic management guidance for the four demo calls, deterministically, from the synthetic actuals."""
    r = _rng(u["ticker"], "guide")
    A = fin["annual"]
    bank = u.get("bank", False)
    ag26 = (A["FY26"]["revenue"] / A["FY25"]["revenue"] - 1) * 100
    g27 = (fin["fy27_revenue"] / A["FY26"]["revenue"] - 1) * 100
    plan = {"ag26": ag26, "g27": g27}
    off_r = float(r.choice([-2.5, -0.5, 0.6, 2.2]))
    mid = ag26 + off_r
    plan["fy26_growth"] = (round(mid - 1), round(mid + 1))
    mid2 = ag26 + off_r * 0.4
    plan["fy26_growth_revised"] = (round(mid2 - 1), round(mid2 + 1))
    off27 = float(r.choice([-1.5, 0.0, 1.5]))
    plan["fy27_growth"] = (round(g27 + off27 - 1), round(g27 + off27 + 1))
    shift = float(r.choice([-1, 1]))
    plan["fy27_growth_revised"] = (plan["fy27_growth"][0] + int(shift), plan["fy27_growth"][1] + int(shift))
    if not bank:
        m26 = A["FY26"]["ebitda"] / A["FY26"]["revenue"] * 100
        plan["fy26_margin"] = round(m26 + float(r.choice([-0.6, 0.4, 1.0])), 1)
        plan["fy27_margin"] = round(m26 + u["md"] + float(r.choice([-0.8, 0.3, 0.9])), 1)
        plan["fy26_capex"] = _round_to(A["FY26"]["capex"] * (1 + float(r.choice([-0.12, 0.03, 0.22]))))
        plan["fy27_capex"] = _round_to(fin["fy27_capex_plan"] * (1 + float(r.choice([-0.1, 0.05, 0.15]))))
    return plan


