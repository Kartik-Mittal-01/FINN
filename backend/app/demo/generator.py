def _annual_report(u: dict, fin: dict) -> list[str]:
    n, bank = u["name"], u.get("bank", False)
    A = fin["annual"]
    r = _rng(u["ticker"], "ar")
    a26, a25 = A["FY26"], A["FY25"]
    g = (a26["revenue"] / a25["revenue"] - 1) * 100
    p1 = [f"{n} - Annual Report FY26 (SAMPLE EXCERPT)", "", "BUSINESS OVERVIEW",
          f"{n} operates in the {u['sector']} sector. The Company reports its business through the following segments.", "",
          "Segment revenue mix (FY26)"]
    p1 += [f"{s} - {p}%" for s, p, _ in u["segments"]] + [""]
    p1 += [f"{s}: {d}." for s, _, d in u["segments"]]
    p2 = [f"{n} - Management Discussion and Analysis (SAMPLE EXCERPT)", "", "FINANCIAL PERFORMANCE"]
    if bank:
        pat_g = (a26["pat"] / a25["pat"] - 1) * 100
        p2 += [f"Total income grew {g:.1f}% to Rs. {a26['revenue']:,.0f} crore in FY26 from Rs. {a25['revenue']:,.0f} crore in FY25.",
               f"Profit before tax was Rs. {a26['pbt']:,.0f} crore and profit after tax was Rs. {a26['pat']:,.0f} crore, a change of {pat_g:.1f}% over FY25.",
               f"Shareholders' equity stood at Rs. {a26['equity']:,.0f} crore at 31 March 2026."]
    else:
        m26, m25 = a26["ebitda"] / a26["revenue"] * 100, a25["ebitda"] / a25["revenue"] * 100
        reason = "driven by operating leverage and a favourable mix" if m26 >= m25 else "due to higher input costs and competitive pricing"
        p2 += [f"Revenue from operations grew {g:.1f}% to Rs. {a26['revenue']:,.0f} crore in FY26 from Rs. {a25['revenue']:,.0f} crore in FY25.",
               f"EBITDA margin was {m26:.1f}% in FY26 compared with {m25:.1f}% in FY25, {reason}.",
               f"Profit before tax was Rs. {a26['pbt']:,.0f} crore and profit after tax was Rs. {a26['pat']:,.0f} crore.",
               f"Cash flow from operations was Rs. {a26['cfo']:,.0f} crore against capital expenditure of Rs. {a26['capex']:,.0f} crore.",
               f"Total borrowings were Rs. {a26['debt']:,.0f} crore at 31 March 2026 (31 March 2025: Rs. {a25['debt']:,.0f} crore); shareholders' equity was Rs. {a26['equity']:,.0f} crore.",
               f"Working capital: receivable days were {a26['receivable_days']:.0f}, inventory days {a26['inventory_days']:.0f} and payable days {a26['payable_days']:.0f}."]
    p3 = [f"{n} - Risks and Concerns (SAMPLE EXCERPT)", "", "KEY RISKS IDENTIFIED BY MANAGEMENT"]
    for i, risk in enumerate(u["risks"], 1):
        p3.append(f"{i}. {risk}. The Risk Management Committee reviews this risk quarterly and mitigation plans are tracked by senior management.")
    cl = a26["revenue"] * (0.006 + 0.01 * float(r.rand()))
    p4 = [f"{n} - Notes to Financial Statements (SAMPLE EXCERPT)", "", "CONTINGENT LIABILITIES",
          f"Claims against the Company not acknowledged as debt amounted to Rs. {cl:,.0f} crore as at 31 March 2026, mainly relating to disputed indirect-tax and regulatory matters.", "",
          "RELATED PARTY TRANSACTIONS",
          f"Transactions with related parties during FY26 were in the ordinary course of business and at arm's length. The aggregate value of material transactions with promoter group entities was Rs. {cl * 1.8:,.0f} crore.", "",
          "INDEPENDENT AUDITOR'S REPORT",
          "The auditors have issued an unmodified opinion on the financial statements. There is no qualification, reservation or adverse remark."]
    return ["\n".join(p1), "\n".join(p2), "\n".join(p3), "\n".join(p4)]


def _write_pdf(path: Path, pages: list[str]):
    import fitz  # PyMuPDF
    doc = fitz.open()
    for text in pages:
        pg = doc.new_page()
        pg.insert_text((54, 40), SAMPLE_BANNER, fontsize=7.5, color=(0.7, 0.1, 0.1))
        rc = pg.insert_textbox(fitz.Rect(54, 56, 541, 800), text, fontsize=10, fontname="helv")
        if rc < 0:
            raise ValueError("demo page overflow")
    path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(path))
    doc.close()


def generate_documents(u: dict, fin: dict, out_dir: Path) -> list[dict]:
    """Writes real PDF files (synthetic content) and returns metadata for ingestion."""
    t = u["ticker"]
    base = out_dir / "demo" / t.replace("&", "and")
    docs = []
    ar = base / "annual_report_FY26.pdf"
    _write_pdf(ar, _annual_report(u, fin))
    docs.append(dict(doc_type="annual_report", title=f"{u['name']} - Annual Report FY26 (sample excerpt)", period="FY26", doc_date="2026-06-30", path=ar))
    plan = guidance_plan(u, fin)
    for c in _calls(u, fin, plan):
        p = base / f"concall_{c['period']}.pdf"
        _write_pdf(p, c["pages"])
        docs.append(dict(doc_type="concall", title=f"{u['name']} - {qlabel(c['period'])} earnings call transcript (sample)", period=c["period"], doc_date=c["date"], path=p))
    return docs
