def generate_financials(u: dict) -> dict:
    """Returns {'annual': {'FY26': {metric: value}}, 'quarterly': {'Q2FY27': {...}}, 'meta': {...}}"""
    t = u["ticker"]
    r = _rng(t, "fin")
    bank = u.get("bank", False)
    g = u["g"]
    rev = {26: float(u["rev"])}
    for y in range(26, 19, -1):
        gr = g + r.normal(0, max(0.8, abs(g) * 0.2))
        rev[y - 1] = rev[y] / (1 + gr / 100)
    gr27 = g + r.normal(0, 0.8)
    rev[27] = rev[26] * (1 + gr27 / 100)

    ann: dict[int, dict] = {y: {"revenue": rev[y]} for y in range(19, 27)}
    fy27 = {"revenue": rev[27]}
    allyrs = {**ann, 27: fy27}

    if bank:
        for y in range(19, 28):
            pbtm = u["pbtm"] + 0.1 * (y - 26) + r.normal(0, 0.6)
            pbt = rev[y] * pbtm / 100
            allyrs[y].update(pbt=pbt, pat=pbt * 0.75, ebitda=None, depreciation=None, finance_cost=None, other_income=None)
        eq = {26: rev[26] * u["eq"] / 100}
        for y in range(26, 19, -1):
            eq[y - 1] = max(eq[y] - allyrs[y]["pat"] * 0.7, eq[y] * 0.5)
        for y in range(19, 27):
            allyrs[y].update(equity=eq[y], debt=None, cash=None, cfo=None, capex=None)
    else:
        m, md, dr, dt = u["m"], u["md"], u["dr"], u["dt"]
        dep_ratio = DEP_RATIO.get(u["sector"], 0.035)
        debt = {26: rev[26] * dr / 100}
        for y in range(26, 19, -1):
            debt[y - 1] = debt[y] / (1 + (dt + r.normal(0, 1.5)) / 100)
        debt[27] = debt[26] * (1 + dt / 100)
        for y in range(19, 28):
            margin = m + md * (y - 26) + r.normal(0, 0.45)
            ebitda = rev[y] * margin / 100
            dep = rev[y] * dep_ratio
            interest = debt[y] * 0.085
            oi = rev[y] * 0.012
            pbt = ebitda - dep - interest + oi
            pat = pbt * 0.75 if pbt > 0 else pbt
            allyrs[y].update(ebitda=ebitda, depreciation=dep, finance_cost=interest, other_income=oi, pbt=pbt, pat=pat, debt=debt[y])
        eq = {26: rev[26] * u["eq"] / 100}
        for y in range(26, 19, -1):
            eq[y - 1] = max(eq[y] - allyrs[y]["pat"] * 0.7, eq[y] * 0.45)
        for y in range(19, 27):
            a = allyrs[y]
            a["equity"] = eq[y]
            a["cash"] = rev[y] * (0.08 + r.normal(0, 0.01))
            cc = u["cc"] + u["ccd"] * (y - 26) + r.normal(0, 0.05)
            a["cfo"] = (a["pat"] + a["depreciation"]) * cc
            a["capex"] = rev[y] * u["cx"] / 100 * (1 + r.normal(0, 0.07))
            drift = 2.0 if u["ccd"] < 0 else -0.7
            a["receivable_days"] = max(0.5, u["dso"] + drift * (y - 26) * -1 + r.normal(0, 1.2))
            a["inventory_days"] = max(0.0, u["dio"] + drift * (y - 26) * -1 + r.normal(0, 1.2))
            a["payable_days"] = max(0.5, u["dpo"] + r.normal(0, 1.5))
        # FY27 capex plan (used for guidance only)
        fy27["capex"] = rev[27] * u["cx"] / 100

    annual = {}
    for y in range(19, 27):
        annual[f"FY{y}"] = {k: (None if v is None else round(float(v), 1 if "days" in k else 0)) for k, v in allyrs[y].items()}

    # ---- quarterly (consistent with annual: weights sum to 1 within a fiscal year)
    quarterly = {}
    for y in (25, 26, 27):
        w = np.array([0.238, 0.246, 0.254, 0.262]) + r.normal(0, 0.004, 4)
        w = w / w.sum()
        nq = 4 if y < 27 else 2
        src = allyrs[y]
        noise = r.normal(0, 0.5, 4)
        noise -= noise.mean()
        for q in range(1, nq + 1):
            qv = {"revenue": src["revenue"] * w[q - 1]}
            if bank:
                pbt = src["pbt"] * w[q - 1] * (1 + noise[q - 1] / 20)
                qv.update(pbt=pbt, pat=pbt * 0.75, ebitda=None, depreciation=None, finance_cost=None, other_income=None)
            else:
                margin = (src["ebitda"] / src["revenue"] * 100) + noise[q - 1]
                if y == 27 and q == 2:
                    margin += u.get("shock", 0)
                ebitda = qv["revenue"] * margin / 100
                dep, fin, oi = src["depreciation"] * w[q - 1], src["finance_cost"] * w[q - 1], src["other_income"] * w[q - 1]
                pbt = ebitda - dep - fin + oi
                qv.update(ebitda=ebitda, depreciation=dep, finance_cost=fin, other_income=oi, pbt=pbt, pat=pbt * 0.75 if pbt > 0 else pbt)
            quarterly[qkey(y, q)] = {k: (None if v is None else round(float(v), 0)) for k, v in qv.items()}
    return {"annual": annual, "quarterly": quarterly, "fy27_capex_plan": fy27.get("capex"), "fy27_revenue": rev[27]}


def financial_rows(ticker: str, fin: dict) -> list[dict]:
    rows = []
    for p, vals in fin["annual"].items():
        for k, v in vals.items():
            rows.append(dict(ticker=ticker, period=p, period_type="annual", period_end=fy_end(int(p[2:])), metric=k, value=v))
    for p, vals in fin["quarterly"].items():
        fy, q = int(p[4:]), int(p[1])
        for k, v in vals.items():
            rows.append(dict(ticker=ticker, period=p, period_type="quarterly", period_end=q_end(fy, q).isoformat(), metric=k, value=v))
    return rows


