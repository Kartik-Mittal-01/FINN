def _rng(ticker: str, salt: str = "") -> np.random.RandomState:
    return np.random.RandomState(zlib.crc32((ticker + salt).encode()) & 0xFFFFFFFF)


def inr(n) -> str:
    """Indian digit grouping: 1234567 -> 12,34,567"""
    if n is None:
        return "-"
    neg = n < 0
    s = f"{abs(round(n)):d}"
    if len(s) > 3:
        head, tail = s[:-3], s[-3:]
        parts = []
        while len(head) > 2:
            parts.insert(0, head[-2:])
            head = head[:-2]
        if head:
            parts.insert(0, head)
        s = ",".join(parts + [tail])
    return f"({s})" if neg else s


def last_trading_day(now: Optional[datetime] = None) -> date:
    now = (now or datetime.now(IST)).astimezone(IST)
    d = now.date()
    if now.hour < 18:  # EOD data is normally published after the close
        d -= timedelta(days=1)
    while d.weekday() >= 5:
        d -= timedelta(days=1)
    return d


# ------------------------------------------------------------------ period helpers
def fy_end(fy: int) -> str:
    return f"20{fy:02d}-03-31"


def q_end(fy: int, q: int) -> date:
    return {1: date(2000 + fy - 1, 6, 30), 2: date(2000 + fy - 1, 9, 30), 3: date(2000 + fy - 1, 12, 31), 4: date(2000 + fy, 3, 31)}[q]


def qkey(fy: int, q: int) -> str:
    return f"Q{q}FY{fy:02d}"


def qlabel(key: str) -> str:
    return f"{key[:2]} {key[2:]}"


