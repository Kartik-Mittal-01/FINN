from datetime import datetime
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException, Query
from fastapi.responses import PlainTextResponse, RedirectResponse
from pydantic import BaseModel
from sqlalchemy.orm import Session

from ..database import get_db
from ..models import Announcement, Holding
from ..services import announcement_classifier as clf
from ..services.prioritisation import PRIORITY_ORDER, score_announcement
from ..services.state import get_setting, is_demo, set_setting
from .deps import ann_out, window_bounds

router = APIRouter(prefix="/api", tags=["announcements"])
RANK = lambda a: (-PRIORITY_ORDER.get(a.priority, 0), -a.attention_score, -a.filed_at.timestamp())


def _query(db, window, start, end, ticker, category, priority, q, scope):
    s, e, label = window_bounds(window, start, end)
    qs = db.query(Announcement).filter(Announcement.filed_at >= s, Announcement.filed_at <= e, Announcement.is_demo == is_demo(db))
    if scope == "holdings":
        qs = qs.filter(Announcement.ticker.in_([h.ticker for h in db.query(Holding).all()] or [""]))
    if ticker:
        qs = qs.filter(Announcement.ticker.in_([x.strip().upper() for x in ticker.split(",")]))
    if category:
        qs = qs.filter(Announcement.category.in_(category.split(",")))
    if priority:
        qs = qs.filter(Announcement.priority.in_(priority.split(",")))
    if q:
        qs = qs.filter(Announcement.headline.ilike(f"%{q}%"))
    return qs.all(), (s, e, label)


@router.get("/announcements")
def list_announcements(window: str = "24h", start: Optional[str] = None, end: Optional[str] = None, ticker: Optional[str] = None,
                       category: Optional[str] = None, priority: Optional[str] = None, q: Optional[str] = None,
                       scope: str = "holdings", db: Session = Depends(get_db)):
    rows, (s, e, label) = _query(db, window, start, end, ticker, category, priority, q, scope)
    seen = get_setting(db, "last_digest_seen")
    return {"window": {"label": label, "start": s.isoformat() + "Z", "end": e.isoformat() + "Z"}, "items": [ann_out(a, seen) for a in sorted(rows, key=RANK)]}


@router.get("/digest")
def digest(window: str = "24h", start: Optional[str] = None, end: Optional[str] = None, ticker: Optional[str] = None,
           category: Optional[str] = None, priority: Optional[str] = None, scope: str = "holdings", db: Session = Depends(get_db)):
    """Prioritised digest: material items first, routine filings collapsed into `routine`."""
    rows, (s, e, label) = _query(db, window, start, end, ticker, category, priority, None, scope)
    seen = get_setting(db, "last_digest_seen")
    rows.sort(key=RANK)
    items = [ann_out(a, seen) for a in rows]
    material = [i for i in items if i["priority"] != "low"]
    routine = [i for i in items if i["priority"] == "low"]
    counts = {p: sum(1 for i in items if i["priority"] == p) for p in ("critical", "high", "medium", "low")}
    companies = {}
    for i in material:
        companies[i["ticker"]] = companies.get(i["ticker"], 0) + 1
    new_n = sum(1 for i in items if i["is_new"])
    parts = [f"{counts['critical']} critical" if counts["critical"] else None, f"{counts['high']} high-priority" if counts["high"] else None,
             f"{counts['medium']} medium" if counts["medium"] else None]
    headline = ", ".join(p for p in parts if p) or "Nothing material"
    return {"window": {"label": label, "start": s.isoformat() + "Z", "end": e.isoformat() + "Z"}, "counts": {**counts, "total": len(items)},
            "headline": f"{headline} across {len(companies)} companies" if companies else "Nothing material in this window – only routine filings." if routine else "No filings in this window.",
            "material": material, "routine": routine, "new_since_last_seen": new_n, "last_seen": seen, "mode": "demo" if is_demo(db) else "live"}


@router.post("/digest/seen")
def mark_seen(db: Session = Depends(get_db)):
    now = datetime.utcnow().isoformat() + "Z"
    set_setting(db, "last_digest_seen", now)
    return {"last_seen": now}


@router.get("/announcements/{aid}")
def get_announcement(aid: int, db: Session = Depends(get_db)):
    a = db.get(Announcement, aid)
    if not a:
        raise HTTPException(404, "Announcement not found")
    return ann_out(a, get_setting(db, "last_digest_seen"), detail=True)


@router.get("/announcements/{aid}/filing")
def filing(aid: int, db: Session = Depends(get_db)):
    a = db.get(Announcement, aid)
    if not a:
        raise HTTPException(404, "Announcement not found")
    if a.is_demo:
        banner = "*** SAMPLE FILING – synthetic text generated by FINN's demo seeder. Not an actual exchange filing. ***\n\n"
        return PlainTextResponse(banner + f"{a.company_name} ({a.ticker})\nFiled: {a.filed_at.isoformat()}Z\n\n{a.headline}\n\n{a.body_text or ''}")
    if a.attachment_url or a.url:
        return RedirectResponse(a.attachment_url or a.url)
    raise HTTPException(404, "No filing link stored")


class ClassifyIn(BaseModel):
    headline: str
    body: Optional[str] = ""
    category_hint: Optional[str] = None


@router.post("/classify")
def classify_preview(body: ClassifyIn):
    """Try the classifier + priority engine on any headline (used by the Settings 'test a headline' box and by tests)."""
    c = clf.classify(body.headline, body.body, use_llm=True)
    p = score_announcement(category=c.category, headline=body.headline, body=body.body or "")
    return {"classification": c.as_dict(), "priority": p}
